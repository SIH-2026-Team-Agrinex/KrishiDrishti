export const localizeCropName = (crop: string, lang: LanguageCode): string => {
  if (!crop) return crop;
  if (lang === 'en') return crop;
  
  // Exact match
  if (CROP_NAMES_MAP[crop]?.[lang]) {
    return CROP_NAMES_MAP[crop][lang];
  }
  
  // Substring match
  const lower = crop.toLowerCase();
  for (const [key, mapping] of Object.entries(CROP_NAMES_MAP)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      if (mapping[lang]) return mapping[lang];
    }
  }
  
  return crop;
};

