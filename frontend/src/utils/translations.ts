export const getTranslation = (lang: LanguageCode, key: string): string => {
  const text = UI_TRANSLATIONS[lang]?.[key] || UI_TRANSLATIONS['en']?.[key];
  if (text) return text;
  
  let parts = key.split('_');
  const prefixes = ['nav', 'hero', 'set', 'auth', 'weather', 'history', 'dash', 'footer', 'analyze', 'step', 'drop'];
  if (prefixes.includes(parts[0])) {
      parts.shift();
  }
  let res = parts.map(p => p.charAt(0).toUpperCase() + p.slice(1)).join(' ');
  return res;
};

